App.t = function (key) {
  const lang = (App.state && App.state.settings && App.state.settings.language) || 'ru';
  const dict = App.i18n[lang] || App.i18n.ru;
  return dict[key] !== undefined ? dict[key] : (App.i18n.ru[key] !== undefined ? App.i18n.ru[key] : key);
};

App.tf = function (key, params) {
  let s = App.t(key);
  for (const k in params) s = s.split('{' + k + '}').join(params[k]);
  return s;
};
